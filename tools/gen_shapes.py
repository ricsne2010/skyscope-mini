#!/usr/bin/env python3
"""Generate shapes.h (aircraft silhouettes + classification tables) for the
SkyScope Mini and Satellite firmware from SkyScope's own Python, so all three
projects draw and classify aircraft the same way.

    python3 tools/gen_shapes.py <path-to-skyscope> > include/shapes.h
"""
import os
import sys
from pathlib import Path

os.environ["PYGAME_HIDE_SUPPORT_PROMPT"] = "1"  # pygame's banner would end up in the header

sys.path.insert(0, str(Path(sys.argv[1]).resolve()))
import symbols  # noqa: E402  (SkyScope's module)

KINDS = ["jet", "heavy", "bizjet", "turboprop", "light", "glider", "heli"]  # 1..7; 0 = triangle

out = []
w = out.append
w("// Generated by tools/gen_shapes.py from SkyScope's symbols.py; do not edit.")
w("#pragma once")
w("#include <cstdint>")
w("")
w("namespace shapes {")
w("")
w("struct Pt { float x, y; };")
w("struct Poly { const Pt* pts; uint8_t n; };")
w("struct Shape { const Poly* polys; uint8_t count; uint8_t length_px; };  // length at a 1080 px scope")
w("")
w("// Kinds: 0 triangle (classic), " + ", ".join(f"{i + 1} {k}" for i, k in enumerate(KINDS)) + ".")
w(f"constexpr int kKindCount = {len(KINDS) + 1};")
w("")
for k in KINDS:
    polys, length = symbols.SHAPES[k]
    for i, poly in enumerate(polys):
        pts = ", ".join(f"{{{x:.3f}f, {y:.3f}f}}" for x, y in poly)
        w(f"constexpr Pt k{k.capitalize()}{i}[] = {{{pts}}};")
    items = ", ".join(f"{{k{k.capitalize()}{i}, {len(p)}}}" for i, p in enumerate(polys))
    w(f"constexpr Poly k{k.capitalize()}Polys[] = {{{items}}};")
    w("")
w("constexpr Shape kShapes[kKindCount] = {")
w("    {nullptr, 0, 0},  // triangle: drawn separately")
for k in KINDS:
    polys, length = symbols.SHAPES[k]
    w(f"    {{k{k.capitalize()}Polys, {len(polys)}, {length}}},  // {k}")
w("};")
w("")

def strlist(name, values):
    vals = ", ".join(f'"{v}"' for v in values)
    w(f"constexpr const char* {name}[] = {{{vals}}};")
    w(f"constexpr int {name}Count = {len(values)};")

w("// Type-code prefixes, as in SkyScope's symbols.classify().")
strlist("kHeliTypes", symbols.HELI_TYPES)
strlist("kTurbopropTypes", symbols.TURBOPROP_TYPES)
strlist("kBizjetTypes", symbols.BIZJET_TYPES)
strlist("kHeavyTypes", symbols.HEAVY_TYPES)
strlist("kLightTypes", symbols.LIGHT_TYPES)
strlist("kAirlinerTypes", symbols.AIRLINER_TYPES)
w("")
w("}  // namespace shapes")
print("\n".join(out))
